package com.crsk.openclaw.node

/**
 * The on-device `act` command. The agent only has openclaw's generic `exec` tool
 * (openclaw 2026.5.12 dropped stdio MCP, so native tap/observe tools can't be
 * registered — see NodeProcess.refreshMcpConfig). This wrapper collapses the
 * ~60-token curl-to-:3001 boilerplate the model used to emit on EVERY step into a
 * ~4-token call: `act tap 5`, `act type 5 hello`, `act observe`. It reads the bearer
 * token from the env openclaw already injects (OPENCLAW_GATEWAY_TOKEN), so the model
 * never spells out the Authorization header or the URL.
 *
 * Authored with `§` standing in for the shell `$` so we don't have to escape every
 * shell variable inside a Kotlin string; [render] swaps it back.
 */
object ActWrapperScript {

    private const val TEMPLATE = """#!/system/bin/sh
# act — thin wrapper over the on-device UI bridge on :3001.
# Generated by NodeProcess; DO NOT EDIT. The agent emits `act <verb> ...` via exec.
B="§{ACT_BRIDGE_URL:-http://127.0.0.1:3001}"
AUTH="Authorization: Bearer §OPENCLAW_GATEWAY_TOKEN"
CT='Content-Type: application/json'
verb="§1"
shift 2>/dev/null
esc() { printf '%s' "§1" | sed 's/\\/\\\\/g; s/"/\\"/g' | tr '\n\r\t' '   '; }
is_int() {
  case "§1" in
    ''|*[!0-9]*) return 1 ;;
    *) return 0 ;;
  esac
}
post() { exec curl -s --noproxy 127.0.0.1,localhost -X POST -H "§CT" -H "§AUTH" -d "§1" "§2"; }
case "§verb" in
  observe|look|read|tree|back|home|recents|notifications|enter|search)
    v="§verb"
    if [ "§v" = "tree" ]; then v="read"; fi
    if [ "§v" = "search" ]; then v="enter"; fi
    post "{\"verb\":\"§v\"}" "§B/agent/act"
    ;;
  tap|double_tap|long_tap|long-tap)
    v="§verb"
    if [ "§v" = "long-tap" ]; then v="long_tap"; fi
    if [ "§#" -ge 2 ] && is_int "§1" && is_int "§2"; then
      post "{\"verb\":\"§v\",\"x\":§1,\"y\":§2}" "§B/agent/act"
    elif is_int "§1"; then
      post "{\"verb\":\"§v\",\"id\":§1}" "§B/agent/act"
    else
      post "{\"verb\":\"§v\",\"text\":\"§(esc "§*")\"}" "§B/agent/act"
    fi
    ;;
  type)
    if is_int "§1"; then
      id="§1"
      shift 2>/dev/null
      post "{\"verb\":\"type\",\"id\":§id,\"text\":\"§(esc "§*")\"}" "§B/agent/act"
    else
      post "{\"verb\":\"type\",\"text\":\"§(esc "§*")\"}" "§B/agent/act"
    fi
    ;;
  scroll)
    dir="§{1:-down}"
    shift 2>/dev/null
    if [ -n "§*" ]; then
      post "{\"verb\":\"scroll\",\"direction\":\"§(esc "§dir")\",\"text\":\"§(esc "§*")\"}" "§B/agent/act"
    else
      post "{\"verb\":\"scroll\",\"direction\":\"§(esc "§dir")\"}" "§B/agent/act"
    fi
    ;;
  swipe)
    if [ "§#" -ge 4 ] && is_int "§1" && is_int "§2" && is_int "§3" && is_int "§4"; then
      post "{\"verb\":\"swipe\",\"x1\":§1,\"y1\":§2,\"x2\":§3,\"y2\":§4}" "§B/agent/act"
    else
      post "{\"verb\":\"swipe\",\"direction\":\"§(esc "§{1:-up}")\"}" "§B/agent/act"
    fi
    ;;
  wait)
    if [ "§#" -eq 0 ]; then
      post "{\"verb\":\"wait\",\"timeout\":3000}" "§B/agent/act"
    elif [ "§#" -eq 1 ] && is_int "§1"; then
      post "{\"verb\":\"wait\",\"timeout\":§1}" "§B/agent/act"
    else
      txt="§1"
      shift 2>/dev/null
      if is_int "§1"; then t="§1"; else t=3000; fi
      post "{\"verb\":\"wait\",\"text\":\"§(esc "§txt")\",\"timeout\":§t}" "§B/agent/act"
    fi
    ;;
  note)
    post "{\"verb\":\"note\",\"text\":\"§(esc "§*")\"}" "§B/agent/act"
    ;;
  take_over)
    post "{\"verb\":\"take_over\",\"reason\":\"§(esc "§*")\"}" "§B/agent/act"
    ;;
  launch)
    post "{\"verb\":\"launch\",\"package\":\"§(esc "§*")\"}" "§B/agent/act"
    ;;
  batch)
    post "{\"ops\":§*}" "§B/ui/batch"
    ;;
  *)
    echo "{\"ok\":false,\"error\":\"unknown act verb: §verb\"}"
    exit 1
    ;;
esac
"""

    fun render(port: Int = 3001): String =
        TEMPLATE.replace("127.0.0.1:3001", "127.0.0.1:$port").replace("§", "$")
}
